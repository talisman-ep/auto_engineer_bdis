from typing import Protocol, TypeVar
from uuid import UUID

from backend.application.dtos import CarFilterDTO, ReviewSearchResultDTO
from backend.domain.entities import (
    CarModel,
    Engineer,
    Manufacturer,
    Review,
    Technology,
)

T = TypeVar("T")
ID = TypeVar("ID")


class CrudRepository(Protocol[T, ID]):
    async def create(self, entity: T) -> T: ...
    async def get_by_id(self, entity_id: ID) -> T | None: ...
    async def list_all(self, limit: int = 50, offset: int = 0) -> list[T]: ...
    async def update(self, entity: T) -> T: ...
    async def delete(self, entity_id: ID) -> bool: ...


class ICarDocumentPort(CrudRepository[CarModel, UUID], Protocol):
    async def filter_cars(self, filters: CarFilterDTO) -> list[CarModel]: ...
    async def get_many_by_ids(self, model_ids: list[UUID]) -> list[CarModel]: ...
    async def upsert_manufacturer(self, manufacturer: Manufacturer) -> Manufacturer: ...
    async def get_manufacturer(self, manufacturer_id: UUID) -> Manufacturer | None: ...
    async def upsert_engineer(self, engineer: Engineer) -> Engineer: ...
    async def get_engineer(self, engineer_id: UUID) -> Engineer | None: ...
    async def upsert_technology(self, tech: Technology) -> Technology: ...


class IReviewSearchPort(CrudRepository[Review, UUID], Protocol):
    async def search_full_text(
        self, query: str, limit: int = 20
    ) -> list[ReviewSearchResultDTO]: ...


class ICarGraphPort(Protocol):
    async def upsert_relations(
        self,
        car: CarModel,
        manufacturer_id: UUID,
        engineer_ids: list[UUID],
        tech_ids: list[UUID],
    ) -> None: ...
    async def get_engineer_model_ids(self, engineer_id: UUID) -> list[UUID]: ...
    async def get_similar_model_ids(
        self, model_id: UUID, limit: int = 5
    ) -> list[UUID]: ...


class ICachePort(Protocol):
    async def get(self, key: str) -> str | None: ...
    async def set(self, key: str, value: str, ttl_seconds: int = 300) -> None: ...
    async def increment_counter(self, name: str, amount: int = 1) -> int: ...